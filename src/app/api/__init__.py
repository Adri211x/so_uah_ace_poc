# API endpoints live here. Each file defines HTTP routes using FastAPI.
#
# Endpoints are THIN -- they should:
#   1. Receive the HTTP request
#   2. Call a service to do the actual work
#   3. Return the response
#
# Endpoints should NOT contain business logic.
# If you find yourself writing if/else logic here, it belongs in a service.
#
# Example: see health.py in this folder.
